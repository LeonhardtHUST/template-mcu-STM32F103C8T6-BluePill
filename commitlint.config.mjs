// 提交信息校验：在 @commitlint/config-conventional 之上补齐 AGENTS.md §1 的中文规范。
//
// 校验边界（重要）：
//   - 机器能判定的：简述中文 / 首字汉字 / ≤50 字 / 结尾无句号、验证等级、
//     构建数字（Flash / RAM）、AI 署名。
//   - 机器判不准的：「动词开头」属于语义判断，中文动词没有可靠词表，
//     强行正则会大量误伤，因此放进根目录 README「提交规范」章节的人工核对清单。
//   - 钩子管格式，AGENTS.md 管代码与生成边界；本仓库不提供任何跳过钩子的方式。
//
// 规则返回 [是否通过, 失败提示]（commitlint plugin rule 约定）。

const SUBJECT_MAX_CHARS = 50;

const chineseSubject = (parsed) => {
  const subject = parsed.subject || '';
  if (!/[\u4e00-\u9fa5]/.test(subject)) {
    return [false, '简述必须使用中文（至少含一个汉字）'];
  }
  if (!/^[\u4e00-\u9fa5]/.test(subject)) {
    return [false, '简述首字必须是汉字；「动词开头」请按 README 提交规范人工核对'];
  }
  const length = Array.from(subject).length;
  if (length > SUBJECT_MAX_CHARS) {
    return [false, `简述不得超过 ${SUBJECT_MAX_CHARS} 字（当前 ${length} 字）`];
  }
  if (/[。．.；;]$/.test(subject)) {
    return [false, '简述结尾不得加句号或分号'];
  }
  return [true, ''];
};

const verifyLevel = (parsed) => {
  // 正文 + footer 都算：验证等级常写在正文，也可能写在结尾。
  const text = `${parsed.body || ''}\n${parsed.footer || ''}`;
  if (/\bL[0-5]\b/.test(text) || /未验证/.test(text)) {
    return [true, ''];
  }
  return [false,
    '正文必须写明验证等级 L0–L5，或明确写「未验证」（见 AGENTS.md §1.5 / §3）'];
};

const buildNumbers = (parsed) => {
  const text = `${parsed.body || ''}\n${parsed.footer || ''}`;
  // 纯文档 / 配置豁免：明确写「未运行构建」即不要求数字。
  if (/未运行构建/.test(text)) {
    return [true, ''];
  }
  // 只有提到构建（或给出 L3）时才要求 Flash / RAM 字节数。
  const mentionsBuild = /pio run|构建|编译|\bL3\b|Flash|RAM/i.test(text);
  if (!mentionsBuild) {
    return [true, ''];
  }
  const hasFlash = /Flash[^\d\n]{0,24}\d[\d,]*/i.test(text);
  const hasRam = /RAM[^\d\n]{0,24}\d[\d,]*/i.test(text);
  if (hasFlash && hasRam) {
    return [true, ''];
  }
  return [false,
    '正文提到构建（pio run / 构建 / L3）时必须同时记录 Flash 与 RAM 字节数；纯文档请写「未运行构建」豁免'];
};

const noAiSignature = (parsed) => {
  const raw = parsed.raw || '';
  if (/(Co-Authored-By|Co-authored-by|Generated\s*(by|with)|Generated-by|AI[- ]?[Gg]enerated)/i.test(raw)) {
    return [false,
      '提交信息禁止 AI 署名尾注（Co-Authored-By / Generated by 等），见 AGENTS.md §1.5'];
  }
  return [true, ''];
};

export default {
  extends: ['@commitlint/config-conventional'],
  plugins: [
    {
      rules: {
        'chinese-subject': chineseSubject,
        'verify-level': verifyLevel,
        'build-numbers': buildNumbers,
        'no-ai-signature': noAiSignature,
      },
    },
  ],
  rules: {
    // config-conventional 的 subject-case 面向英文大小写；中文简述不适用，
    // 首字汉字与长度已由 chinese-subject 覆盖，避免误伤。
    'subject-case': [0],
    'chinese-subject': [2, 'always'],
    'verify-level': [2, 'always'],
    'build-numbers': [2, 'always'],
    'no-ai-signature': [2, 'always'],
  },
};
